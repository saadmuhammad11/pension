"""The AG's own payroll statement, read as structured facts.

The Monthly Salary Statement is generated by the Accountant General's payroll system, not
typed by a department, and it states in plain fields what the rest of the bundle only
implies: the servant's grade, the pay scale they sit on, **which stage of it**, their basic
pay, their date of birth, and the date they entered service.

The stage is the important one. Basic pay is not an arbitrary figure -- it is a position on
a published scale, moved one step by each annual increment. A statement saying "BPS 14, Pay
Stage 23" fixes the whole history: the pay at every earlier year is the earlier stage of the
same table. That is what turns the three-year average required by rule 4.4(4) from three
numbers an officer must find and type into an arithmetic the engine can do -- once the scale
table itself is loaded (it is not yet; see ``rules/packs``).

Read from OCR rather than from the vision model, deliberately. Asked for a grade the model
once returned "BS. 12" for a BS-19 officer at confidence 1.00, and every figure here decides
either a rupee amount or which documents the office demands.

The patterns are tolerant because the scans are poor. A real statement came back with
"Pay seals" for "Pay scale", "CNR" for "CNIC", "Personal Number" for "Personnel Number" and
a date of birth whose dots had all become spaces. None of that changes what the page says.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date

#: The statement repeats itself on a poor scan -- the pay block came back eight times over
#: on a real page. Every pattern therefore takes the FIRST match and ignores the rest: a
#: loop that repeats a correct value is harmless, and the first occurrence is the one the
#: reader saw before it began looping.
_PERSONNEL = re.compile(r"Person\w*\s*Number\s*[:.]?\s*(\d{6,10})", re.I)
_CNIC = re.compile(r"\bCN[IR]C?\b\s*[:.]?\s*([\d\s.-]{13,20})", re.I)
_DOB = re.compile(r"Date\s*of\s*Birth\s*[:.]?\s*(\d{1,2})[.\s/-](\d{1,2})[.\s/-](\d{4})", re.I)
_ENTRY = re.compile(
    r"Entry\s*into\s*Govt\.?\s*Service\s*[:.]?\s*(\d{1,2})[.\s/-](\d{1,2})[.\s/-](\d{4})", re.I)
_LENGTH = re.compile(
    r"Length\s*of\s*Service\s*[:.]?\s*(\d+)\s*Years?\s*(\d+)\s*Months?\s*(\d+)\s*Days?", re.I)
#: "Pay scale: BPS For - 2022" -- which revision of the scale the servant sits on. Without
#: it a stage number is meaningless, because a revision renumbers the table.
_SCALE_YEAR = re.compile(r"BPS\s*For\s*[:.-]?\s*-?\s*(\d{4})", re.I)
#: "BPS: 14". The letters in "BPS For" stop this matching the scale year by accident.
_BPS = re.compile(r"\bBPS\s*[:.]?\s*(\d{1,2})(?!\d)", re.I)
_STAGE = re.compile(r"Pay\s*Stage\s*[:.]?\s*(\d{1,2})(?!\d)", re.I)
_BASIC = re.compile(r"Basic\s*Pay\s*[:.]?\s*([\d,]+)(?:\.\d\d)?", re.I)
_MONTH = re.compile(r"Monthly\s*Salary\s*Statement\s*\(([A-Za-z]+)\s*-\s*(\d{4})\)", re.I)


@dataclass(frozen=True)
class PayrollFacts:
    """What the payroll statement states. Every field optional: a page may not carry it."""

    personnel_no: str | None = None
    cnic: str | None = None
    date_of_birth: date | None = None
    entry_into_service: date | None = None
    length_of_service: str | None = None
    pay_scale_year: int | None = None
    bps: int | None = None
    pay_stage: int | None = None
    basic_pay: int | None = None
    statement_month: str | None = None

    @property
    def locates_on_the_scale(self) -> bool:
        """Enough to walk the pay back through earlier years, once a table is loaded.

        All three are needed together. A stage without its scale year cannot be looked up,
        because a pay revision renumbers the table; a grade without a stage names a column
        and not a cell.
        """
        return None not in (self.pay_scale_year, self.bps, self.pay_stage)


def _date(m: re.Match | None) -> date | None:
    if not m:
        return None
    day, month, year = (int(g) for g in m.groups())
    try:
        return date(year, month, day)
    except ValueError:
        # A misread day or month. Refused rather than clamped: this date sets qualifying
        # service and the superannuation check, and a plausible wrong date is worse here
        # than none at all.
        return None


def _int(m: re.Match | None, low: int, high: int) -> int | None:
    if not m:
        return None
    value = int(m.group(1).replace(",", ""))
    return value if low <= value <= high else None


def payroll_facts_on(text: str) -> PayrollFacts:
    """Parse an AG Monthly Salary Statement. Fields it does not state come back None."""
    text = text or ""
    cnic = None
    if (m := _CNIC.search(text)):
        digits = "".join(c for c in m.group(1) if c.isdigit())
        cnic = digits if len(digits) == 13 else None
    month = _MONTH.search(text)
    return PayrollFacts(
        personnel_no=(m.group(1) if (m := _PERSONNEL.search(text)) else None),
        cnic=cnic,
        date_of_birth=_date(_DOB.search(text)),
        entry_into_service=_date(_ENTRY.search(text)),
        length_of_service=(" ".join(m.groups()) + " (y m d)"
                           if (m := _LENGTH.search(text)) else None),
        # A scale year outside living memory is a misread of some other four-digit number.
        pay_scale_year=_int(_SCALE_YEAR.search(text), 1970, 2100),
        bps=_int(_BPS.search(text), 1, 22),
        # Punjab scales run to about 30 stages; a larger number is not a stage.
        pay_stage=_int(_STAGE.search(text), 1, 40),
        basic_pay=_int(_BASIC.search(text), 1, 10_000_000),
        statement_month=(f"{month.group(1).title()} {month.group(2)}" if month else None),
    )
