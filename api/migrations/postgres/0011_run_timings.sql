-- 0011 for PostgreSQL: run_timings with an identity column where sqlite had INTEGER PRIMARY KEY.
-- Columns as in ../0011_run_timings.sql. pipeline.timing and the GP Fund module's reading/timing.py
-- create the same table if they find it missing (dbcore.run_timings_ddl).
CREATE TABLE IF NOT EXISTS run_timings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      TEXT NOT NULL,
    kind        TEXT NOT NULL,               -- stage | model | queue
    stage       TEXT NOT NULL,
    name        TEXT,
    page        INTEGER,
    started_at  TEXT NOT NULL,
    ended_at    TEXT NOT NULL,
    duration_s  DOUBLE PRECISION NOT NULL,
    queue_s     DOUBLE PRECISION,
    pages       INTEGER,
    status      TEXT NOT NULL DEFAULT 'ok',  -- ok | error
    detail_json TEXT
);
CREATE INDEX IF NOT EXISTS run_timings_run ON run_timings(run_id, started_at);
